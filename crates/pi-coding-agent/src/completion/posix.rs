//! bash and zsh scripts. Both complete the value of the option before the cursor first, then the
//! words of a subcommand, then options, subcommands, and files.

use super::{commands, ident, spellings, value_list, valued_options};
use crate::cli::table::{CLI_COMMANDS, ValueKind, completable_options, option_words};
use crate::resources::brand::APP_NAME;

/// `text` as one single-quoted shell word.
fn single_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

/// The `case` arms that complete option values in bash.
fn bash_value_arms() -> String {
    let app = APP_NAME;
    let mut arms = String::new();
    for option in valued_options() {
        let body = match option.kind {
            ValueKind::Model | ValueKind::Provider => {
                let list = value_list(option.kind);
                format!(
                    "COMPREPLY=($(compgen -W \"$({app} completion --values {list} 2>/dev/null)\" -- \"$cur\"))\n            \
                     if declare -F __ltrim_colon_completions >/dev/null 2>&1; then __ltrim_colon_completions \"$cur\"; fi"
                )
            }
            ValueKind::Choice(choices) => format!("COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))", choices.join(" ")),
            ValueKind::File => {
                "compopt -o filenames 2>/dev/null\n            COMPREPLY=($(compgen -f -- \"$cur\"))".into()
            }
            ValueKind::Dir => {
                "compopt -o filenames 2>/dev/null\n            COMPREPLY=($(compgen -d -- \"$cur\"))".into()
            }
            _ => "compopt +o default 2>/dev/null\n            COMPREPLY=()".into(),
        };
        arms.push_str(&format!(
            "        {})\n            {body}\n            return 0\n            ;;\n",
            spellings(option).join("|")
        ));
    }
    arms
}

pub fn bash() -> String {
    let app = APP_NAME;
    let name = format!("_{}_completion", ident());
    let mut subcommands = String::new();
    for (command, words) in commands() {
        subcommands.push_str(&format!(
            "            {command})\n                COMPREPLY=($(compgen -W \"{}\" -- \"$cur\"))\n                return 0\n                ;;\n",
            words.join(" ")
        ));
    }
    let names: Vec<&str> = CLI_COMMANDS.iter().map(|command| command.name).collect();
    format!(
        "# bash completion for {app}. Generated by `{app} completion bash`.
{name}() {{
    local cur prev cword
    local -a words
    if declare -F _get_comp_words_by_ref >/dev/null 2>&1; then
        _get_comp_words_by_ref -n =: cur prev words cword
    else
        cur=\"${{COMP_WORDS[COMP_CWORD]}}\"
        prev=\"${{COMP_WORDS[COMP_CWORD-1]}}\"
        words=(\"${{COMP_WORDS[@]}}\")
        cword=$COMP_CWORD
    fi
    case \"$prev\" in
{arms}    esac
    if [[ $cword -gt 1 ]]; then
        case \"${{words[1]}}\" in
{subcommands}        esac
    fi
    if [[ $cur == -* ]]; then
        COMPREPLY=($(compgen -W \"{options}\" -- \"$cur\"))
    elif [[ $cword -eq 1 ]]; then
        COMPREPLY=($(compgen -W \"{names}\" -- \"$cur\"))
    fi
    return 0
}}
complete -o default -F {name} {app}
",
        arms = bash_value_arms(),
        options = option_words().join(" "),
        names = names.join(" "),
    )
}

/// The `case` arms that complete option values in zsh.
fn zsh_value_arms(prefix: &str) -> String {
    let mut arms = String::new();
    for option in valued_options() {
        let body = match option.kind {
            ValueKind::Model | ValueKind::Provider => format!("{prefix}_values {}", value_list(option.kind)),
            ValueKind::Choice(choices) => format!("compadd -- {}", choices.join(" ")),
            ValueKind::File => "_files".into(),
            ValueKind::Dir => "_files -/".into(),
            _ => format!("_message {}", single_quoted(option.value.unwrap_or("value"))),
        };
        arms.push_str(&format!("    ({}) {body}; return ;;\n", spellings(option).join("|")));
    }
    arms
}

/// `name:description` entries for `_describe`, one per line.
fn zsh_describe_entries(entries: impl Iterator<Item = (&'static str, &'static str)>) -> String {
    entries.map(|(name, help)| format!("    {}\n", single_quoted(&format!("{name}:{help}")))).collect()
}

pub fn zsh() -> String {
    let app = APP_NAME;
    let prefix = format!("_{}", ident());
    let options = completable_options().flat_map(|option| {
        let help = option.help.first().copied().unwrap_or_default();
        spellings(option).into_iter().map(move |spelling| (spelling, help))
    });
    let names = CLI_COMMANDS.iter().map(|command| (command.name, command.help));
    let mut subcommands = String::new();
    for (command, words) in commands() {
        subcommands.push_str(&format!("      ({command}) compadd -- {} || _files; return ;;\n", words.join(" ")));
    }
    format!(
        "#compdef {app}
# zsh completion for {app}. Generated by `{app} completion zsh`.

{prefix}_values() {{
  local -a values
  values=(${{(f)\"$({app} completion --values $1 2>/dev/null)\"}})
  compadd -a values
}}

{prefix}() {{
  case ${{words[CURRENT-1]}} in
{arms}  esac
  if (( CURRENT > 2 )); then
    case ${{words[2]}} in
{subcommands}    esac
  fi
  if [[ $PREFIX == -* ]]; then
    local -a opts
    opts=(
{options}    )
    _describe -t options option opts
    return
  fi
  if (( CURRENT == 2 )); then
    local -a subcmds
    subcmds=(
{names}    )
    _describe -t commands command subcmds
  fi
  _files
}}

if [[ ${{zsh_eval_context[-1]}} == loadautofunc ]]; then
  {prefix} \"$@\"
else
  compdef {prefix} {app}
fi
",
        arms = zsh_value_arms(&prefix),
        options = zsh_describe_entries(options),
        names = zsh_describe_entries(names),
    )
}
