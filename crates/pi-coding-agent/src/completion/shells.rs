//! fish and PowerShell scripts.

use super::{commands, spellings, value_list, valued_options};
use crate::cli::table::{CLI_COMMANDS, CliOption, ValueKind, completable_options, option_words};
use crate::resources::brand::APP_NAME;

/// `text` in fish single quotes, where `\` and `'` take a backslash.
fn fish_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\\', r"\\").replace('\'', r"\'"))
}

/// The fish `complete` switch for one flag spelling: `-l name`, `-s n`, or `-o nt`.
pub(super) fn fish_flag(spelling: &str) -> String {
    match spelling.strip_prefix("--") {
        Some(long) => format!("-l {long}"),
        None => {
            let short = spelling.trim_start_matches('-');
            if short.chars().count() == 1 { format!("-s {short}") } else { format!("-o {short}") }
        }
    }
}

fn fish_option(app: &str, option: &CliOption) -> String {
    let flags: Vec<String> = spellings(option).iter().map(|spelling| fish_flag(spelling)).collect();
    let value = match option.kind {
        ValueKind::None => String::new(),
        ValueKind::Model | ValueKind::Provider => {
            let list = value_list(option.kind);
            format!(" -x -a {}", fish_quoted(&format!("({app} completion --values {list} 2>/dev/null)")))
        }
        ValueKind::Choice(choices) => format!(" -x -a {}", fish_quoted(&choices.join(" "))),
        ValueKind::File => " -r -F".into(),
        ValueKind::Dir => " -x -a '(__fish_complete_directories)'".into(),
        ValueKind::Text => " -x".into(),
    };
    let help = option.help.first().copied().unwrap_or_default();
    format!("complete -c {app} {}{value} -d {}\n", flags.join(" "), fish_quoted(help))
}

pub fn fish() -> String {
    let app = APP_NAME;
    let mut script = format!("# fish completion for {app}. Generated by `{app} completion fish`.\n");
    for command in CLI_COMMANDS {
        script.push_str(&format!(
            "complete -c {app} -n __fish_use_subcommand -a {} -d {}\n",
            command.name,
            fish_quoted(command.help)
        ));
    }
    for option in completable_options() {
        script.push_str(&fish_option(app, option));
    }
    for (command, words) in commands() {
        let condition = fish_quoted(&format!("__fish_seen_subcommand_from {command}"));
        let (flags, plain): (Vec<&str>, Vec<&str>) = words.iter().partition(|word| word.starts_with('-'));
        if !plain.is_empty() {
            script.push_str(&format!("complete -c {app} -n {condition} -a {}\n", fish_quoted(&plain.join(" "))));
        }
        for word in flags {
            script.push_str(&format!("complete -c {app} -n {condition} {}\n", fish_flag(word)));
        }
    }
    script
}

/// `text` in PowerShell single quotes, where `'` doubles.
fn ps_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', "''"))
}

fn ps_list<'a>(items: impl IntoIterator<Item = &'a str>) -> String {
    let quoted: Vec<String> = items.into_iter().map(ps_quoted).collect();
    format!("@({})", quoted.join(", "))
}

pub fn powershell() -> String {
    let app = APP_NAME;
    let mut values = String::new();
    for option in valued_options() {
        let body = match option.kind {
            ValueKind::Model | ValueKind::Provider => {
                format!("$candidates = @(& {} completion --values {} 2>$null)", ps_quoted(app), value_list(option.kind))
            }
            ValueKind::Choice(choices) => format!("$candidates = {}", ps_list(choices.iter().copied())),
            // Nothing returned: PowerShell falls back to file paths.
            _ => "return".into(),
        };
        for spelling in spellings(option) {
            values.push_str(&format!("        {} {{ {body} }}\n", ps_quoted(spelling)));
        }
    }
    let mut subcommands = String::new();
    for (command, words) in commands() {
        subcommands.push_str(&format!("        {} = {}\n", ps_quoted(command), ps_list(words.iter().copied())));
    }
    format!(
        "# PowerShell completion for {app}. Generated by `{app} completion powershell`.
Register-ArgumentCompleter -Native -CommandName {quoted_app} -ScriptBlock {{
    param($wordToComplete, $commandAst, $cursorPosition)
    $options = {options}
    $commands = {names}
    $subcommands = @{{
{subcommands}    }}
    $words = @($commandAst.CommandElements |
        Where-Object {{ $_.Extent.EndOffset -le $cursorPosition }} |
        ForEach-Object {{ $_.ToString() }})
    if ($wordToComplete -ne '' -and $words.Count -gt 0) {{
        $words = @($words | Select-Object -First ($words.Count - 1))
    }}
    $prev = if ($words.Count -gt 0) {{ $words[$words.Count - 1] }} else {{ '' }}
    $command = if ($words.Count -gt 1) {{ $words[1] }} else {{ '' }}
    $candidates = $null
    switch -Exact -CaseSensitive ($prev) {{
{values}    }}
    if ($null -eq $candidates) {{
        if ($words.Count -gt 1 -and $subcommands.ContainsKey($command)) {{
            $candidates = $subcommands[$command]
        }} elseif ($wordToComplete.StartsWith('-')) {{
            $candidates = $options
        }} elseif ($words.Count -le 1) {{
            $candidates = $commands
        }} else {{
            return
        }}
    }}
    $candidates | Where-Object {{ $_.StartsWith($wordToComplete) }} | ForEach-Object {{
        [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
    }}
}}
",
        quoted_app = ps_quoted(app),
        options = ps_list(option_words()),
        names = ps_list(CLI_COMMANDS.iter().map(|command| command.name)),
    )
}
