/// The syntax for a language name or alias, matched case-insensitively.
pub(crate) fn resolve_syntax(language: &str) -> Option<&'static SyntaxReference> {
    let lower = language.trim().to_ascii_lowercase();
    let (_, name) = ALIASES.iter().find(|(alias, _)| *alias == lower)?;
    SYNTAX_SET.find_syntax_by_name(name)
}

/// Every language name and alias that [`resolve_syntax`] accepts.
pub fn supported_languages() -> Vec<&'static str> {
    ALIASES.iter().filter(|(_, name)| SYNTAX_SET.find_syntax_by_name(name).is_some()).map(|(alias, _)| *alias).collect()
}
