// internal/test_snapshot: t.assert.snapshot and t.assert.fileSnapshot, ported from Node's
// lib/internal/test_runner/snapshot.js. Snapshot files are JavaScript that assigns `exports`.
const { strictEqual } = require("assert");
const { mkdirSync, readFileSync, writeFileSync } = require("fs");
const { dirname } = require("path");
const { codeError, validate } = require("internal/errors");

const kMissingSnapshotTip = "Missing snapshots can be generated by rerunning the command with the --test-update-snapshots flag.";
const defaultSerializers = [(value) => JSON.stringify(value, null, 2)];
const invalidState = (message) => codeError(Error, "ERR_INVALID_STATE", `Invalid state: ${message}`);

let resolveSnapshotPathFn = (testPath) => (typeof testPath === "string" ? `${testPath}.snapshot` : testPath);
let serializerFns = defaultSerializers;

function validateFunctionArray(fns, name) {
  validate.array(fns, name);
  for (let i = 0; i < fns.length; ++i) validate.function(fns[i], `${name}[${i}]`);
}

function setResolveSnapshotPath(fn) {
  validate.function(fn, "fn");
  resolveSnapshotPathFn = fn;
}

function setDefaultSnapshotSerializers(serializers) {
  validateFunctionArray(serializers, "serializers");
  serializerFns = serializers.slice();
}

function escapeSnapshotKey(text) {
  return JSON.stringify(text, null, 2).slice(1, -1).replaceAll("`", "\\`").replaceAll("${", "\\${");
}

function templateEscape(value) {
  return String(value).replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
}

function fileError(kind, error, filename) {
  let message = `Cannot ${kind} snapshot file '${filename}.'`;
  if (kind === "read" && error?.code === "ENOENT") message += ` ${kMissingSnapshotTip}`;
  return Object.assign(invalidState(message), { cause: error, filename });
}

class SnapshotFile {
  constructor(snapshotFile) {
    this.snapshotFile = snapshotFile;
    this.snapshots = { __proto__: null };
    this.nameCounts = new Map();
    this.loaded = false;
  }

  getSnapshot(id) {
    if (!(id in this.snapshots)) {
      const error = invalidState(`Snapshot '${id}' not found in '${this.snapshotFile}.' ${kMissingSnapshotTip}`);
      throw Object.assign(error, { snapshot: id, filename: this.snapshotFile });
    }
    return this.snapshots[id];
  }

  setSnapshot(id, value) {
    this.snapshots[escapeSnapshotKey(id)] = value;
  }

  nextId(name) {
    const count = this.nameCounts.get(name) ?? 1;
    this.nameCounts.set(name, count + 1);
    return `${name} ${count}`;
  }

  readFile() {
    if (this.loaded) return;
    try {
      const source = readFileSync(this.snapshotFile, "utf8");
      const context = { __proto__: null, exports: { __proto__: null } };
      const vm = require("vm");
      vm.createContext(context);
      vm.runInContext(source, context);
      if (context.exports === null || typeof context.exports !== "object") {
        throw invalidState(`Malformed snapshot file '${this.snapshotFile}'.`);
      }
      for (const key in context.exports) this.snapshots[key] = templateEscape(context.exports[key]);
      this.loaded = true;
    } catch (error) {
      throw fileError("read", error, this.snapshotFile);
    }
  }

  writeFile() {
    try {
      const keys = Object.keys(this.snapshots).sort();
      const output = keys.map((key) => `exports[\`${key}\`] = \`${this.snapshots[key]}\`;\n`).join("\n");
      mkdirSync(dirname(this.snapshotFile), { recursive: true });
      writeFileSync(this.snapshotFile, output, "utf8");
    } catch (error) {
      throw fileError("write", error, this.snapshotFile);
    }
  }
}

function serializeValue(value, serializers) {
  try {
    let result = value;
    for (const fn of serializers) result = fn(result);
    return result;
  } catch (error) {
    throw Object.assign(invalidState("The provided serializers did not generate a string."), { input: value, cause: error });
  }
}

// One per test harness: it reads snapshot files once, or with `updateSnapshots` collects new
// snapshots and writes them when the run ends.
class SnapshotManager {
  constructor(updateSnapshots) {
    this.updateSnapshots = updateSnapshots;
    this.cache = new Map();
  }

  resolveSnapshotFile(entryFile) {
    let snapshotFile = this.cache.get(entryFile);
    if (snapshotFile === undefined) {
      const resolved = resolveSnapshotPathFn(entryFile);
      if (typeof resolved !== "string") throw Object.assign(invalidState("Invalid snapshot filename."), { filename: resolved });
      snapshotFile = new SnapshotFile(resolved);
      snapshotFile.loaded = this.updateSnapshots;
      this.cache.set(entryFile, snapshotFile);
    }
    return snapshotFile;
  }

  writeSnapshotFiles() {
    if (!this.updateSnapshots) return;
    for (const snapshotFile of this.cache.values()) snapshotFile.writeFile();
  }

  // The assertions run with the TestContext as `this`, for its filePath and fullName.
  createAssert() {
    const manager = this;
    return function snapshot(actual, options = {}) {
      validate.object(options, "options");
      const { serializers = serializerFns } = options;
      validateFunctionArray(serializers, "options.serializers");
      const snapshotFile = manager.resolveSnapshotFile(this.filePath);
      const value = `\n${templateEscape(serializeValue(actual, serializers))}\n`;
      const id = snapshotFile.nextId(this.fullName);
      if (manager.updateSnapshots) {
        snapshotFile.setSnapshot(id, value);
      } else {
        snapshotFile.readFile();
        strictEqual(value, snapshotFile.getSnapshot(id));
      }
    };
  }

  createFileAssert() {
    const manager = this;
    return function fileSnapshot(actual, path, options = {}) {
      validate.string(path, "path");
      validate.object(options, "options");
      const { serializers = serializerFns } = options;
      validateFunctionArray(serializers, "options.serializers");
      const value = serializeValue(actual, serializers);
      if (manager.updateSnapshots) {
        try {
          mkdirSync(dirname(path), { recursive: true });
          writeFileSync(path, value, "utf8");
        } catch (error) {
          throw fileError("write", error, path);
        }
        return;
      }
      let expected;
      try {
        expected = readFileSync(path, "utf8");
      } catch (error) {
        throw fileError("read", error, path);
      }
      strictEqual(value, expected);
    };
  }
}

// --test-update-snapshots on the command line, in NODE_OPTIONS, or in run()'s execArgv.
function updateRequested(execArgv = []) {
  const options = String(process.env.NODE_OPTIONS ?? "").split(/\s+/);
  return [...(process.execArgv || []), ...execArgv, ...options].includes("--test-update-snapshots");
}

module.exports = { SnapshotManager, setDefaultSnapshotSerializers, setResolveSnapshotPath, updateRequested };
