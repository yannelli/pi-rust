// Generates the Unicode tables in pi-tui/src/utils/ from Node's ICU data and get-east-asian-width.
// Usage: node gen_unicode_tables.mjs <get-east-asian-width dir> <unicode emoji data dir> <output dir>
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const [eawDir, emojiDir, outDir] = process.argv.slice(2);
if (!eawDir || !emojiDir || !outDir) throw new Error("usage: gen_unicode_tables.mjs <eaw dir> <emoji dir> <out dir>");
const eaw = await import(pathToFileURL(path.join(eawDir, "lookup-data.js")).href);
const eawVersion = JSON.parse(fs.readFileSync(path.join(eawDir, "package.json"), "utf8")).version;
const header = (what) =>
	`//! ${what}\n//! Generated by tools/gen_unicode_tables.mjs (Node ${process.versions.node}, ICU ${process.versions.icu}, ` +
	`Unicode ${process.versions.unicode}).\n//! Do not edit by hand; rerun the generator instead.\n\n`;
const hex = (cp) => `0x${cp.toString(16).toUpperCase().padStart(4, "0")}`;

function packLines(items, indent = "    ", width = 116) {
	const lines = [];
	let line = indent;
	for (const item of items) {
		const piece = `${item},`;
		if (line.length + piece.length + 1 > width && line.trim()) {
			lines.push(line.trimEnd());
			line = indent;
		}
		line += `${piece} `;
	}
	if (line.trim()) lines.push(line.trimEnd());
	return lines.join("\n");
}

function rangesOf(pred) {
	const out = [];
	let start = -1;
	for (let cp = 0; cp <= 0x110000; cp++) {
		const inSet = cp <= 0x10ffff && !(cp >= 0xd800 && cp <= 0xdfff) && pred(cp);
		if (inSet && start < 0) start = cp;
		if (!inSet && start >= 0) {
			out.push([start, cp - 1]);
			start = -1;
		}
	}
	return out;
}

// East Asian Width: fullwidth and wide ranges, copied from get-east-asian-width.
function pairs(flat) {
	const out = [];
	for (let i = 0; i < flat.length; i += 2) out.push(`(${hex(flat[i])}, ${hex(flat[i + 1])})`);
	return out;
}
fs.writeFileSync(
	path.join(outDir, "eaw_table.rs"),
	header(`East Asian Width ranges from get-east-asian-width ${eawVersion} (fullwidth and wide only).`) +
		"/// Inclusive code point ranges with East_Asian_Width=F.\n#[rustfmt::skip]\n" +
		`pub(crate) static FULLWIDTH_RANGES: &[(u32, u32)] = &[\n${packLines(pairs(eaw.fullwidthRanges))}\n];\n\n` +
		"/// Inclusive code point ranges with East_Asian_Width=W.\n#[rustfmt::skip]\n" +
		`pub(crate) static WIDE_RANGES: &[(u32, u32)] = &[\n${packLines(pairs(eaw.wideRanges))}\n];\n`,
);

// Character classes used by graphemeWidth, evaluated with the same regexes as upstream utils.ts.
const zeroWidth = /^(?:\p{Default_Ignorable_Code_Point}|\p{Control}|\p{Mark}|\p{Surrogate})$/v;
const nonPrinting = /^(?:\p{Default_Ignorable_Code_Point}|\p{Control}|\p{Format}|\p{Mark}|\p{Surrogate})$/v;
const mark = /^\p{Mark}$/v;
const spacingMark =
	/^(?:[\p{Spacing_Mark}--[\u{1734}\u{302e}\u{302f}]]|[\u{65f}\u{f7f}\u{102b}\u{102c}\u{1031}\u{1033}-\u{1035}\u{1038}\u{103a}-\u{103e}])$/v;
const flagsOf = (cp) => {
	const ch = String.fromCodePoint(cp);
	return (zeroWidth.test(ch) ? 1 : 0) | (nonPrinting.test(ch) ? 2 : 0) | (mark.test(ch) ? 4 : 0) | (spacingMark.test(ch) ? 8 : 0);
};
const classRanges = [];
{
	let start = -1;
	let current = 0;
	for (let cp = 0; cp <= 0x110000; cp++) {
		const flags = cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff) ? 0 : flagsOf(cp);
		if (flags !== current) {
			if (current !== 0) classRanges.push(`(${hex(start)}, ${hex(cp - 1)}, ${current})`);
			start = cp;
			current = flags;
		}
	}
}
fs.writeFileSync(
	path.join(outDir, "char_class_table.rs"),
	header("Character classes for grapheme width (Default_Ignorable, Control, Format, Mark, spacing marks).") +
		"/// Inclusive code point ranges and their class bits; see the constants in `width.rs`.\n#[rustfmt::skip]\n" +
		`pub(crate) static CHAR_CLASS_RANGES: &[(u32, u32, u8)] = &[\n${packLines(classRanges)}\n];\n`,
);

// RGI emoji, split by sequence type and checked against /^\p{RGI_Emoji}$/v.
const rgi = /^\p{RGI_Emoji}$/v;
const S = (...cps) => String.fromCodePoint(...cps);
const isTone = (cp) => cp >= 0x1f3fb && cp <= 0x1f3ff;
const basic = rangesOf((cp) => rgi.test(S(cp)));
const vs16 = rangesOf((cp) => rgi.test(S(cp, 0xfe0f)));
const modBases = rangesOf((cp) => rgi.test(S(cp, 0x1f3fb)));
for (const [a, b] of modBases)
	for (let cp = a; cp <= b; cp++)
		for (let t = 0x1f3fb; t <= 0x1f3ff; t++) if (!rgi.test(S(cp, t))) throw new Error(`partial tones ${hex(cp)}`);
for (let cp = 0; cp <= 0x10ffff; cp++) {
	if (cp >= 0xd800 && cp <= 0xdfff) continue;
	for (let t = 0x1f3fc; t <= 0x1f3ff; t++) if (rgi.test(S(cp, t)) && !rgi.test(S(cp, 0x1f3fb))) throw new Error("tone");
}
const keycaps = [];
for (let cp = 0; cp < 0x80; cp++) {
	if (rgi.test(S(cp, 0xfe0f, 0x20e3))) keycaps.push(String.fromCharCode(cp));
	if (rgi.test(S(cp, 0x20e3))) throw new Error("keycap without VS16");
}
if (keycaps.join("") !== "#*0123456789") throw new Error(`unexpected keycaps ${keycaps.join("")}`);
const flags = [];
for (let a = 0; a < 26; a++)
	for (let b = 0; b < 26; b++)
		if (rgi.test(S(0x1f1e6 + a, 0x1f1e6 + b))) flags.push(String.fromCharCode(65 + a, 65 + b));

const parseSeqFile = (file, type) =>
	fs
		.readFileSync(path.join(emojiDir, file), "utf8")
		.split("\n")
		.filter((l) => l && !l.startsWith("#") && l.split(";")[1]?.trim() === type)
		.map((l) => l.split(";")[0].trim());
const tags = parseSeqFile("emoji-sequences.txt", "RGI_Emoji_Tag_Sequence").map((s) => s.split(/\s+/).map((h) => parseInt(h, 16)));
for (const t of tags) if (!rgi.test(S(...t)) || t[0] !== 0x1f3f4 || t.at(-1) !== 0xe007f) throw new Error("tag");
const zwj = parseSeqFile("emoji-zwj-sequences.txt", "RGI_Emoji_ZWJ_Sequence").map((s) =>
	s.split(/\s+/).map((h) => parseInt(h, 16)),
);
for (const z of zwj) if (!rgi.test(S(...z))) throw new Error(`zwj not RGI in this Node: ${z.map(hex)}`);
// Cross-check the structural sets against emoji-sequences.txt.
for (const type of ["Basic_Emoji", "Emoji_Keycap_Sequence", "RGI_Emoji_Flag_Sequence", "RGI_Emoji_Modifier_Sequence"])
	for (const entry of parseSeqFile("emoji-sequences.txt", type)) {
		const m = entry.match(/^([0-9A-F]+)\.\.([0-9A-F]+)$/);
		const seqs = m
			? Array.from({ length: parseInt(m[2], 16) - parseInt(m[1], 16) + 1 }, (_, i) => [parseInt(m[1], 16) + i])
			: [entry.split(/\s+/).map((h) => parseInt(h, 16))];
		for (const s of seqs) if (!rgi.test(S(...s))) throw new Error(`${type} ${s.map(hex)}`);
	}

// ZWJ sequences: group by skeleton (tones removed) and encode the tone variants compactly.
const elementsOf = (seq) => {
	const els = [[]];
	for (const cp of seq) cp === 0x200d ? els.push([]) : els.at(-1).push(cp);
	return els;
};
const groups = new Map();
for (const seq of zwj) {
	const els = elementsOf(seq);
	const tones = els.map((e) => (e.length > 1 && isTone(e[1]) ? e[1] - 0x1f3fb : -1));
	els.forEach((e, i) => {
		if (e.slice(tones[i] >= 0 ? 2 : 1).some(isTone) || (tones[i] >= 0 && e.length !== 2)) throw new Error("tone position");
		if (e.slice(1).some((c) => c !== 0xfe0f && !isTone(c))) throw new Error(`unexpected element ${e.map(hex)}`);
	});
	const skel = els.map((e) => e.filter((c) => !isTone(c)));
	const key = skel
		.map((e) => e.map((c, i) => (i > 0 && c === 0xfe0f ? "!" : c.toString(16).toUpperCase())).join(""))
		.join("-");
	if (!groups.has(key)) groups.set(key, []);
	groups.get(key).push(tones);
}
const expand = (key, mode, n) => {
	if (mode === "") return [Array(n).fill(-1)];
	const plain = !mode.endsWith("x");
	const slots = [...mode.replace("x", "").replace("d", "")].map(Number);
	const distinct = mode.includes("d");
	const out = plain ? [Array(n).fill(-1)] : [];
	const rec = (i, acc) => {
		if (i === slots.length) {
			if (distinct && new Set(acc).size !== acc.length) return;
			const t = Array(n).fill(-1);
			slots.forEach((s, j) => (t[s] = acc[j]));
			out.push(t);
			return;
		}
		for (let v = 0; v < 5; v++) rec(i + 1, [...acc, v]);
	};
	rec(0, []);
	return out;
};
const zwjEntries = [];
for (const [key, variants] of groups) {
	const n = variants[0].length;
	const want = new Set(variants.map((t) => t.join(",")));
	const slots = [...new Set(variants.flatMap((t) => t.map((v, i) => (v >= 0 ? i : -1)).filter((i) => i >= 0)))].sort();
	if (slots.some((i) => i > 9)) throw new Error(`tone slot index above 9 in ${key}`);
	const digits = slots.join("");
	const candidates = slots.length === 0 ? [""] : [digits, `${digits}x`, `${digits}d`, `${digits}dx`];
	const mode = candidates.find((m) => {
		const got = expand(key, m, n).map((t) => t.join(","));
		return got.length === want.size && got.every((t) => want.has(t));
	});
	if (mode === undefined) throw new Error(`cannot encode tone variants of ${key}`);
	zwjEntries.push(mode ? `${key}:${mode}` : key);
}
function strLines(items, width = 116) {
	const lines = [];
	let line = "    ";
	for (const item of items) {
		if (line.length + item.length + 3 > width && line.trim()) {
			lines.push(`${line}\\`);
			line = "    ";
		}
		line += `${item} `;
	}
	lines.push(`${line}\\`);
	return lines.join("\n");
}
const rangeItems = (rs) => rs.map(([a, b]) => `(${hex(a)}, ${hex(b)})`);
fs.writeFileSync(
	path.join(outDir, "emoji_table.rs"),
	header(`RGI emoji sequences (Emoji ${process.versions.unicode}), matching /^\\p{RGI_Emoji}$/v in Node.`) +
		"/// Code points that are RGI emoji on their own.\n#[rustfmt::skip]\n" +
		`pub(crate) static BASIC_RANGES: &[(u32, u32)] = &[\n${packLines(rangeItems(basic))}\n];\n\n` +
		"/// Code points that are RGI emoji when followed by U+FE0F.\n#[rustfmt::skip]\n" +
		`pub(crate) static VS16_RANGES: &[(u32, u32)] = &[\n${packLines(rangeItems(vs16))}\n];\n\n` +
		"/// Code points that take any of the five skin tone modifiers.\n#[rustfmt::skip]\n" +
		`pub(crate) static MODIFIER_BASE_RANGES: &[(u32, u32)] = &[\n${packLines(rangeItems(modBases))}\n];\n\n` +
		"/// Keycap bases (each followed by U+FE0F U+20E3).\npub(crate) static KEYCAP_BASES: &str = " +
		`"${keycaps.join("")}";\n\n` +
		"/// Region pairs of the RGI flag sequences, as ASCII letters A..Z for U+1F1E6..U+1F1FF.\n" +
		`pub(crate) static FLAG_REGIONS: &str = "\\\n${strLines(flags)}\n";\n\n` +
		"/// Tag sequences as code point lists.\n#[rustfmt::skip]\n" +
		`pub(crate) static TAG_SEQUENCES: &[&[u32]] = &[\n${tags.map((t) => `    &[${t.map(hex).join(", ")}],`).join("\n")}\n];\n\n` +
		"/// ZWJ sequences: hex elements joined by '-' (implied U+200D), '!' for U+FE0F after the base, then an\n" +
		"/// optional ':' tone mode: element digits taking tones, 'd' for distinct tones only, 'x' for no untoned variant.\n" +
		`pub(crate) static ZWJ_SEQUENCES: &str = "\\\n${strLines(zwjEntries)}\n";\n`,
);
