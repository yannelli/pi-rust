#!/usr/bin/env node
// Usage: node scripts/builtin-providers.mjs <upstream pi checkout with node_modules and model data>
// Writes the provider metadata of upstream `builtinProviders()` for the extension host.
import { writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const upstream = resolve(process.argv[2] ?? "");
if (!process.argv[2]) throw new Error("Usage: node scripts/builtin-providers.mjs <upstream-root>");
const out = join(dirname(fileURLToPath(import.meta.url)), "../crates/pi-coding-agent/src/extensions/js/builtin_providers.js");

const PACKAGES = { "pi-ai": "ai", "pi-telemetry": "telemetry", "pi-tui": "tui", "pi-agent-core": "agent" };
registerHooks({
	resolve(specifier, context, next) {
		const match = /^@earendil-works\/(pi-[a-z-]+)(\/.*)?$/.exec(specifier);
		const dir = match && PACKAGES[match[1]];
		if (!dir) return next(specifier, context);
		const entry = match[2] ? match[2].slice(1) : "index";
		return next(pathToFileURL(join(upstream, "packages", dir, "src", `${entry}.ts`)).href, context);
	},
});

const all = await import(pathToFileURL(join(upstream, "packages/ai/src/providers/all.ts")).href);
const providers = all.builtinProviders().map((provider) => {
	const { apiKey, oauth } = provider.auth;
	const entry = { id: provider.id, name: provider.name };
	if (provider.baseUrl !== undefined) entry.baseUrl = provider.baseUrl;
	if (provider.headers !== undefined) entry.headers = provider.headers;
	if (apiKey) entry.apiKey = apiKey.name;
	if (oauth) {
		entry.oauth = { name: oauth.name };
		if (oauth.isSubscription !== undefined) entry.oauth.isSubscription = oauth.isSubscription;
		if (oauth.loginLabel !== undefined) entry.oauth.loginLabel = oauth.loginLabel;
	}
	return entry;
});

const lines = providers.map((entry) => `\t${JSON.stringify(entry)},`);
const source = [
	"// Generated by `node scripts/builtin-providers.mjs <upstream>` from upstream `builtinProviders()`.",
	"export const BUILTIN_PROVIDERS = [",
	...lines,
	"];",
	"",
].join("\n");
writeFileSync(out, source);
console.log(`Wrote ${providers.length} providers to ${out}`);
