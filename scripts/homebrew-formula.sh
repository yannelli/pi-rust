#!/bin/sh
# Print the Homebrew formula for a release: scripts/homebrew-formula.sh <version> <SHA256SUMS>
# The Release workflow pushes the output to yannelli/homebrew-tap as Formula/pi.rb.

set -eu

[ $# -eq 2 ] || {
	printf 'usage: %s <version> <SHA256SUMS>\n' "$0" >&2
	exit 2
}
version=$1
sums=$2

sha() {
	name="pi-v$version-$1.tar.gz"
	hash=$(awk -v want="$name" '{ n = $2; sub(/^\*/, "", n); sub(/\r$/, "", n); if (n == want) { print tolower($1); exit } }' "$sums")
	[ -n "$hash" ] || {
		printf 'error: %s is not in %s\n' "$name" "$sums" >&2
		exit 1
	}
	printf '%s' "$hash"
}

mac_arm=$(sha aarch64-apple-darwin)
mac_intel=$(sha x86_64-apple-darwin)
linux_arm=$(sha aarch64-unknown-linux-musl)
linux_intel=$(sha x86_64-unknown-linux-musl)

cat <<EOF
# Generated by scripts/homebrew-formula.sh in yannelli/pi-rust. Do not edit by hand.
class Pi < Formula
  desc "Interactive coding agent CLI for the pi agent harness"
  homepage "https://github.com/yannelli/pi-rust"
  license "MIT"

  on_macos do
    on_arm do
      url "https://github.com/yannelli/pi-rust/releases/download/v$version/pi-v$version-aarch64-apple-darwin.tar.gz"
      sha256 "$mac_arm"
    end
    on_intel do
      url "https://github.com/yannelli/pi-rust/releases/download/v$version/pi-v$version-x86_64-apple-darwin.tar.gz"
      sha256 "$mac_intel"
    end
  end

  on_linux do
    on_arm do
      url "https://github.com/yannelli/pi-rust/releases/download/v$version/pi-v$version-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$linux_arm"
    end
    on_intel do
      url "https://github.com/yannelli/pi-rust/releases/download/v$version/pi-v$version-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$linux_intel"
    end
  end

  def install
    bin.install "pi"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/pi --version")
  end
end
EOF
